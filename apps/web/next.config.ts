import type { NextConfig } from "next";

const isProd = process.env.NODE_ENV === "production";
const api = process.env.NEXT_PUBLIC_API_URL ?? "";

// 'unsafe-inline' for scripts/styles is a conscious compromise (Next inlines its bootstrap and Tailwind emits style tags);
// the upgrade path is nonce-based CSP. Everything else is locked down: no third-party origins at all.
const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  `connect-src 'self' ${api}`.trim(),
  "media-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "upgrade-insecure-requests",
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "no-referrer" },
  { key: "Permissions-Policy", value: "microphone=(self), camera=(), geolocation=(), payment=(), interest-cohort=()" },
  { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
];

const nextConfig: NextConfig = {
  poweredByHeader: false,
  turbopack: {
    rules: {
      "*.css": { loaders: ["@tailwindcss/turbopack"], as: "*.css" },
    },
  },
  async headers() {
    // development needs eval/HMR, so the strict policy is production-only
    return isProd ? [{ source: "/:path*", headers: securityHeaders }] : [];
  },
};

export default nextConfig;
