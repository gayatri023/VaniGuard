// Generates app/theme.generated.css from ONE seed colour using Google's Material Color Utilities.
// Run: npm run theme   (bundles with esbuild because the package uses extensionless ESM imports)
import { argbFromHex, hexFromArgb, themeFromSourceColor } from "@material/material-color-utilities";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const SEED = "#00696b"; // deep teal: Material-native, not a bank/UPI brand colour
const theme = themeFromSourceColor(argbFromHex(SEED), [
  { name: "success", value: argbFromHex("#2e7d32"), blend: true },
  { name: "warning", value: argbFromHex("#b26a00"), blend: true },
]);

const kebab = (s) => s.replace(/([A-Z])/g, "-$1").toLowerCase();
const NEUTRAL_TONES = {
  light: { "surface-container-lowest": 100, "surface-container-low": 96, "surface-container": 94, "surface-container-high": 92, "surface-container-highest": 90 },
  dark: { "surface-container-lowest": 4, "surface-container-low": 10, "surface-container": 12, "surface-container-high": 17, "surface-container-highest": 22 },
};

function vars(mode) {
  const scheme = theme.schemes[mode].toJSON();
  const out = {};
  for (const [k, v] of Object.entries(scheme)) out[kebab(k)] = hexFromArgb(v);
  for (const [k, tone] of Object.entries(NEUTRAL_TONES[mode])) out[k] = hexFromArgb(theme.palettes.neutral.tone(tone));
  for (const c of theme.customColors) {
    const g = c[mode];
    const n = c.color.name;
    out[n] = hexFromArgb(g.color);
    out[`on-${n}`] = hexFromArgb(g.onColor);
    out[`${n}-container`] = hexFromArgb(g.colorContainer);
    out[`on-${n}-container`] = hexFromArgb(g.onColorContainer);
  }
  return out;
}
const light = vars("light");
const dark = vars("dark");
const block = (o) => Object.entries(o).map(([k, v]) => `  --md-sys-color-${k}: ${v};`).join("\n");
const map = Object.keys(light).map((k) => `  --color-${k}: var(--md-sys-color-${k});`).join("\n");

writeFileSync(
  join(process.cwd(), "app", "theme.generated.css"), // run from apps/web via `npm run theme`
  `/* GENERATED by scripts/gen-theme.mjs from seed ${SEED}. Do not edit by hand. */\n` +
    `:root {\n  color-scheme: light dark;\n${block(light)}\n}\n` +
    `@media (prefers-color-scheme: dark) {\n  :root {\n${block(dark).replace(/^/gm, "  ")}\n  }\n}\n` +
    `@theme inline {\n${map}\n}\n`,
);
console.log(`theme: ${Object.keys(light).length} colour roles, light + dark, seed ${SEED}`);
