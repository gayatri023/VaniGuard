// Extracts the Material Symbols (rounded, weight 400) paths we use into components/icons.ts.
import { readFileSync, writeFileSync } from "node:fs";

const NAMES = ["mic", "stop", "check_circle", "check", "warning", "info", "edit", "arrow_forward", "content_copy", "delete", "translate",
  "share", "refresh", "person", "close", "lock", "volume_up", "bar_chart", "download", "speed", "schedule", "error", "shield", "tune",
  "keyboard", "payments", "verified_user", "arrow_back", "visibility", "timer", "query_stats"];
const dir = new URL("../node_modules/@material-symbols/svg-400/rounded/", import.meta.url);
const out = {};
for (const n of NAMES) {
  try {
    out[n] = /<path d="([^"]+)"/.exec(readFileSync(new URL(`${n}.svg`, dir), "utf8"))[1];
  } catch {
    console.warn("missing icon:", n);
  }
}
writeFileSync(new URL("../components/icons.ts", import.meta.url),
  `// GENERATED by scripts/gen-icons.mjs from @material-symbols/svg-400 (Apache-2.0). Do not edit by hand.\n` +
  `export const ICONS: Record<string, string> = ${JSON.stringify(out, null, 1)};\n` +
  `export type IconName = ${NAMES.filter((n) => out[n]).map((n) => `"${n}"`).join(" | ")};\n`);
console.log(`icons: ${Object.keys(out).length}`);
