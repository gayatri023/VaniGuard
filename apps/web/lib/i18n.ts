export type Lang = "en" | "hi";
export const STRINGS: Record<Lang, Strings> = { en, hi };

export function useLang(): [Lang, () => void] {
  const saved = useStored("vg_lang");
  const lang: Lang = saved === "hi" ? "hi" : "en";
  const toggle = () => writeStored("vg_lang", lang === "en" ? "hi" : "en");
  return [lang, toggle];
}
